"""Evon-powered workflows after the first call, each with a labelled fallback:
  - technician voice update  -> new status + spoken message for the owner
  - spoken service report    -> structured report
  - voice history question   -> answer from past tickets (uses Evon's long context)
"""
import json
import re

import config
from core.language import NAMES
from reasoner import evon
from reasoner.prompts import HISTORY_SYSTEM, REPORT_SYSTEM, UPDATE_SYSTEM

STATUS_WORDS = [  # checked in order: "fixed" wins over "reached"
    ("fixed", ["theek ho gaya", "thik ho gaya", "theek kar diya", "chalu ho gaya", "chal rahi hai", "fixed",
               "repaired", "done", "ठीक हो गया", "ठीक कर दिया", "चालू हो गया"]),
    ("on_site", ["pahunch gaya", "pahuch gaya", "reached", "arrived", "check kar raha", "dekh raha",
                 "पहुँच गया", "पहुंच गया"]),
    ("on_the_way", ["nikal raha", "nikal gaya", "raste mein", "aa raha hoon", "on the way", "leaving",
                    "निकल गया", "रास्ते में"]),
]
OWNER_MSG = {
    "fixed": "Aapki machine theek ho gayi hai.",
    "on_site": "Technician pahunch gaye hain aur machine check kar rahe hain.",
    "on_the_way": "Technician raste mein hain.",
    "assigned": "Technician ne update diya hai.",
}


def _lang_name(code: str) -> str:
    return NAMES.get(code, "Hinglish")


def _evon_json(system: str, user: str, max_tokens: int = 600) -> dict:
    reply = evon._chat([{"role": "system", "content": system}, {"role": "user", "content": user}],
                       max_tokens=max_tokens, json_mode=True)
    return evon.extract_json(reply)


# ---------- technician update ----------
def fallback_update(text: str) -> dict:
    t = text.lower()
    status = next((s for s, words in STATUS_WORDS if any(w in t for w in words)), "assigned")
    parts = re.findall(r"(\w+)\s+(?:chahiye|lagega|badalna)", t)
    return {"status": status, "summary_en": text[:160], "owner_message": OWNER_MSG[status],
            "parts_needed": parts[:3], "engine": "fallback"}


def tech_update(text: str, ticket: dict, owner_language: str) -> dict:
    if config.EVON_BASE_URL:
        try:
            d = _evon_json(UPDATE_SYSTEM.replace("{owner_language}", _lang_name(owner_language)),
                           f"Ticket: {json.dumps(ticket, ensure_ascii=False)[:1500]}\n\nTechnician said: {text}")
            if d.get("status") not in ("on_the_way", "on_site", "fixed", "assigned"):
                d["status"] = fallback_update(text)["status"]
            d["engine"] = "evon"
            return d
        except (evon.EvonUnavailable, ValueError, json.JSONDecodeError):
            pass
    return fallback_update(text)


# ---------- service report ----------
def fallback_report(text: str, ticket: dict) -> dict:
    return {"work_done": [s.strip() for s in re.split(r"[.।]\s*", text) if s.strip()][:5],
            "root_cause": (ticket.get("probable_causes") or [{"cause": "Not recorded"}])[0].get("cause", ""),
            "parts_replaced": [], "time_spent_hours": None,
            "recommendations": ["Schedule a preventive maintenance check."],
            "warranty_note": "", "owner_summary": "Repair complete. Report attached.", "engine": "fallback"}


def service_report(text: str, ticket: dict, owner_language: str) -> dict:
    if config.EVON_BASE_URL:
        try:
            d = _evon_json(REPORT_SYSTEM.replace("{owner_language}", _lang_name(owner_language)),
                           f"Ticket: {json.dumps(ticket, ensure_ascii=False)[:2000]}\n\nTechnician summary: {text}",
                           max_tokens=800)
            d["engine"] = "evon"
            return d
        except (evon.EvonUnavailable, ValueError, json.JSONDecodeError):
            pass
    return fallback_report(text, ticket)


