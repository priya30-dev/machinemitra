# ---------- history question ----------
def _compact(tickets: list[dict]) -> list[dict]:
    import time
    out = []
    for r in tickets:
        t = r.get("ticket") or {}
        out.append({"id": r["id"], "date": time.strftime("%d %b %Y", time.localtime(r["created"])),
                    "machine": r["machine_type"], "status": r["status"], "urgency": r["urgency"],
                    "symptoms": t.get("symptoms", []), "parts": t.get("parts_to_carry", []),
                    "report": (r.get("report") or {}).get("work_done", [])})
    return out


def fallback_history(question: str, tickets: list[dict]) -> dict:
    q = question.lower()
    hits = [t for t in _compact(tickets)
            if any(w in q for w in t["machine"].split() if len(w) > 3)] or _compact(tickets)
    if not hits:
        return {"answer": "Abhi tak koi repair record nahi mila.", "engine": "fallback", "tickets": []}
    last = hits[0]
    return {"answer": f"Pichhli shikayat {last['date']} ko {last['machine']} ki thi, status {last['status']}. "
                      f"Is machine ke kul {len(hits)} record hain.", "engine": "fallback",
            "tickets": [h["id"] for h in hits[:5]]}


def answer_history(question: str, tickets: list[dict], owner_language: str) -> dict:
    if config.EVON_BASE_URL and tickets:
        try:
            answer = evon._chat([
                {"role": "system", "content": HISTORY_SYSTEM.replace("{owner_language}", _lang_name(owner_language))},
                {"role": "user", "content": f"Question: {question}\n\nTickets: "
                                            f"{json.dumps(_compact(tickets), ensure_ascii=False)}"},
            ], max_tokens=300)
            return {"answer": answer, "engine": "evon", "tickets": [t["id"] for t in tickets[:5]]}
        except evon.EvonUnavailable:
            pass
    return fallback_history(question, tickets)
